import sympy as sp
import json
r=[]
def check(name,value):
    r.append({'id':name,'passed':bool(value)})
Q=sp.Rational
n,u,v,b,c,A,s,L,T=sp.symbols('n u v b c A s L T',real=True)
x,m,N=sp.symbols('x m N',positive=True)
check('equation_steps',all(sp.solve(e,n)==[3] for e in [Q(8,100)*n-Q(24,100),100*Q(8,100)*n-100*Q(24,100),8*n-24,8*n/8-Q(24,8),n-3]))
check('reverse_order',sp.reduce_inequalities(u<v,u)==sp.reduce_inequalities(-u>-v,u))
check('negative_power',sp.simplify(x**b-1/x**(-b))==0)
check('derivative_identity',sp.diff(x,x)==1)
check('derivative_log',sp.diff(sp.log(x),x)==1/x)
check('derivative_exp',sp.diff(sp.exp(x),x)==sp.exp(x))
y=sp.Function('y')
check('derivative_log_composition',sp.diff(sp.log(y(x)),x)==sp.diff(y(x),x)/y(x))
check('derivative_log_constant',sp.diff(sp.log(A),n)==0)
check('derivative_scaled_log',sp.diff(b*sp.log(x),x)==b/x)
check('derivative_negative_linear',sp.diff(-c*n,n)==-c)
check('derivative_affine',sp.diff(A+b*s,s)==b)
check('numerator_rewrite',sp.cancel(b/x-c-(b-c*x)/x)==0)
d,k=sp.symbols('d k',positive=True)
check('numerator_increasing',sp.expand((b+k*(n+d))-(b+k*n))==k*d and (k*d).is_positive)
check('positive_square',(x**2).is_positive)
check('negative_coefficient',sp.reduce_inequalities(-c>0,c)==sp.reduce_inequalities(c<0,c))
check('empirical_width',sp.cancel((Q(14,100)-Q(3,100))/N-Q(11,100)/N)==0)
check('surprise_base',sp.simplify(-sp.log(x,2)+sp.log(x)/sp.log(2))==0)
check('constant_recovery',sp.simplify((m*L)/m-L)==0 and sp.solve(T-m*L,L)==[T/m])
check('maximum_rounding',Q(-227,1000)/Q(-67,10000)==Q(227,1000)/Q(67,10000)==Q(2270,67) and abs(Q(2270,67)-Q(3388,100))<Q(1,200))
aa=sp.symbols('aa',positive=True)
check('positive_factors',aa.is_positive and (x**b).is_positive and sp.exp(-c*x).is_positive and (aa*x**b*sp.exp(-c*x)).is_positive)
check('surprise_nonnegative',sp.reduce_inequalities(-sp.log(x)/sp.log(2)>=0,x)==(x<=1))
check('maximum_integer_rounding',abs(Q(2270,67)-34)<Q(1,2))
print(json.dumps({'passed':all(a['passed'] for a in r),'results':r}))
raise SystemExit(0 if all(a['passed'] for a in r) else 1)
